/** 网文标题进猜词池：词=标题，close=标题里的关键意象（猜中任一部分给"接近"） */
export const GUESS_TITLES: WordOption[] = RELAY_TITLES.slice(1).map((t) => {
  const job = JOB.find((j) => t.includes(j))
  const role = ROLE.find((r) => t.includes(r))
  const world = WORLD.find((w) => t.includes(w))
  const keys = [...new Set([job, role, world].filter((x): x is string => !!x))]
  return { word: t, drawing: matchDrawing(t), level: '网文', close: keys.length ? keys : [t.slice(-3)] }
})

/* ---------- 汇总词池 ---------- */

/** 猜词总池：内置单词 + 词组 + 网文标题 + 房规自定义词 */
export function guessPool(rules: RoomRules): WordOption[] {
  const custom = (rules.wordBank ?? [])
    .map((w) => w.trim())
    .filter(Boolean)
    .map((w): WordOption => ({ word: w, drawing: matchDrawing(w), level: '自定义', close: [] }))
  return [...GUESS_WORDS, ...GUESS_PHRASES, ...GUESS_TITLES, ...custom]
}
