const pick = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)]

interface Slots {
  w: string
  r: string
  c: string
  j: string
  t: string
  p: string
}

const TITLE_TEMPLATES: ((s: Slots) => string)[] = [
  ({ w, j }) => `我在${w}${j}`,
  ({ w, c }) => `${w}：开局捡到${c}`,
  ({ w, r }) => `重生之${w}${r}传奇`,
  ({ w, r }) => `${w}第一${r}`,
  ({ w, c }) => `带着${c}闯${w}`,
  ({ w, r }) => `${w}之${r}崛起`,
  ({ c, p }) => `我的${p}是${c}`,
  ({ w, j, t }) => `${t}！${w}${j}日常`,
  ({ w, r }) => `${r}在${w}`,
  ({ w, r }) => `穿越${w}当${r}`,
  ({ w, r }) => `${w}直播：${r}求生记`,
  ({ w, r, j }) => `${w}：${r}被迫${j}`,
]

/** 生成一条网文式标题（传话题目 / 猜词难题） */
export function rollRelayTitle(): string {
  const s: Slots = { w: pick(WORLD), r: pick(ROLE), c: pick(CHEAT), j: pick(JOB), t: pick(TONE), p: pick(PROP) }
  return pick(TITLE_TEMPLATES)(s)
}

