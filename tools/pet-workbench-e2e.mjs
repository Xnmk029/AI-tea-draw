import assert from 'node:assert/strict'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fixture, output, sleep, until } from './net-test-helpers.mjs'

const checks = []
const check = (name, condition, detail) => { assert.ok(condition, name); checks.push({ name, detail }); console.log(`✓ ${name}`) }
const f = await fixture()
try {
  const agent = await f.newAgent('真实试画测试茶宠')
  const page = await f.newPage('pet-workbench', f.bridges[0], { mcp: agent.port })
  await page.waitScreen('home')
  await agent.waitGame()
  const health = async () => (await fetch(`http://127.0.0.1:${agent.port}/`)).json()
  const room = await agent.tool('room_state')
  check('不开房就建立绘画上下文与真实MCP连接', room.context === 'sandbox' && room.room === 'pet-sandbox' && f.hub.rooms.size === 0)
  await page.click('我的茶宠', '.main-menu button')
  await until(() => page.js("!!document.querySelector('.pet-workbench')"), '工作台显示')
  check('主菜单显示真实Agent身份', await page.js("document.querySelector('.home-tr .hud-chip').textContent.includes('真实试画测试茶宠') && document.querySelector('.pet-head').textContent.includes('真实 Agent 已连接')"))
  check('试画纸没有预置假作品', await page.js("document.querySelectorAll('[data-pet-op]').length === 0"))
  const socketCount = () => page.js(`window.__netTestSockets.filter(socket=>new URL(socket.url).port==='${agent.port}').length`)
  check('应用只有一条Agent连接', await socketCount() === 1)
  const select = async (label, value) => {
    await page.js(`(()=>{const input=document.querySelector('select[aria-label='+${JSON.stringify(JSON.stringify(label))}+']');if(!input||input.disabled)throw Error('找不到select');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(input,${JSON.stringify(value)});input.dispatchEvent(new Event('change',{bubbles:true}));})()`)
    await sleep(100)
  }
  const paperIds = () => page.js("[...document.querySelectorAll('.pet-draw-main [data-pet-op]')].map(el=>el.dataset.petOp)")
  const trialText = '画一只茶壶，保持壶嘴朝右'
  await page.click('绘画风格', '.pet-tabs button')
  await page.click('几何极简', '.pet-style-choices button')
  await page.setInput('textarea[aria-label="额外绘画要求"]', '使用三个主要形状，保留右上角留白。')
  await page.setInput('input[aria-label="风格预设名称"]', '回归几何风格')
  await page.click('保存预设')
  check('保存自定义风格预设', await page.js("[...document.querySelector('select[aria-label=\"已保存风格预设\"]').options].some(option=>option.textContent==='回归几何风格')"))
  await page.click('试画与调试', '.pet-tabs button')
  await select('试画落笔指引', 'center')
  await page.setInput('textarea[aria-label="试画提示词"]', trialText)
  await page.click('发送真实试画')
  const task = (await agent.tool('turn_get_task')).task
  check('风格和补充指令进入真实MCP任务', task.text.includes(trialText) && task.text.includes('几何极简') && task.text.includes('三个主要形状') && task.contextId && task.taskId)
  check('任务领取状态由真实工具回执更新', await page.js("document.querySelector('.pet-task-status').textContent.includes('Agent 已领取')"))
  const targets = (await agent.tool('canvas_get_targets')).targets
  const svg = '<circle cx="80" cy="80" r="50" fill="none" stroke="#3B3A36" stroke-width="4"/><path d="M125 60 Q185 40 170 105" fill="none" stroke="#3B3A36" stroke-width="4"/><path d="M40 50 Q5 30 10 85 Q10 115 35 110" fill="none" stroke="#3B3A36" stroke-width="4"/><text>不得出现</text><script>alert(1)</script>'
  const draft = await agent.tool('canvas_draw', { svg, targetId: targets[0].id, taskId: task.taskId, contextId: task.contextId, mode: 'commit' })
  check('助手档真实提交降级草稿且SVG过滤有效', draft.previewId && draft.removed.includes('<text>') && draft.removed.includes('<script>'))
  check('盖章前不落入正式笔迹', (await paperIds()).length === 0 && await page.js("!!document.querySelector('.pet-ghost')"))
  await page.click('盖章落笔')
  await until(() => page.js("document.querySelector('.pet-task-status').textContent.includes('真实作画完成')"), '试画实际动画完成')
  check('真实盖章产生Agent笔迹', (await paperIds()).length === 3)
  check('试画全流程没有创建房间', f.hub.rooms.size === 0)
  await page.shot('pet-01-real-drawing')
  await page.click('记录与对比', '.pet-tabs button')
  check('记录保存真实作品和完整提示词', await page.js("document.querySelector('.pet-history-detail').textContent.includes('几何极简') && document.querySelector('.pet-history-detail').textContent.includes('三个主要形状') && document.querySelectorAll('.pet-history-detail [data-pet-op]').length===3"))
  await page.click('绘画风格', '.pet-tabs button')
  await page.click('简笔卡通', '.pet-style-choices button')
  await page.click('记录与对比', '.pet-tabs button')
  await page.click('用当前风格在新纸上画同题')
  const comparedTask = (await agent.tool('turn_get_task')).task
  check('同题试画恢复空白基线并采用新风格', comparedTask.text.includes(trialText) && comparedTask.text.includes('简笔卡通') && (await paperIds()).length === 0)
  const comparedTargets = (await agent.tool('canvas_get_targets')).targets
  await agent.tool('canvas_draw', { svg: '<circle cx="80" cy="80" r="40" fill="none" stroke="#3B3A36" stroke-width="3"/>', targetId: comparedTargets[0].id, taskId: comparedTask.taskId, contextId: comparedTask.contextId })
  await page.click('盖章落笔')
  await until(() => page.js("document.querySelector('.pet-task-status').textContent.includes('真实作画完成')"), '同题第二幅完成')
  await page.click('记录与对比', '.pet-tabs button')
  const bValue = await page.js("[...document.querySelector('select[aria-label=\"对比作品B\"]').options].find(option=>option.value)?.value")
  await select('对比作品B', bValue)
  check('A/B显示两种真实风格且条件相同', await page.js("document.querySelectorAll('.pet-compare-papers [data-pet-op]').length === 4 && !document.querySelector('.pet-comparison .pet-error')"))
  await page.shot('pet-03-style-comparison')
  await page.click('试画与调试', '.pet-tabs button')
  await page.click('清空试画纸')
  await page.click('少墨慢笔测试')
  await page.setInput('textarea[aria-label="试画提示词"]', '检验墨量不足后的修稿')
  await page.click('发送真实试画')
  const limitedTask = (await agent.tool('turn_get_task')).task
  check('调试限制进入真实任务且不改变个人风格', limitedTask.ink.allowance === 1000 && limitedTask.rules.svgPreset === 'strict' && limitedTask.rules.penSpeed === 100 && limitedTask.text.includes('简笔卡通'))
  const limitedSpace = (await agent.tool('canvas_find_space', { w: 400, h: 240 })).space
  const longLine = '<path d="M0 30 L380 30 L0 70 L380 70 L0 110 L380 110 L0 150" fill="none" stroke="#333333" stroke-width="3"/>'
  await assert.rejects(() => agent.tool('canvas_draw', { svg: longLine, spaceId: limitedSpace.id, taskId: limitedTask.taskId, contextId: limitedTask.contextId }), /墨量不足/)
  check('墨量拒绝在界面可见且不产生假图', await page.js("document.querySelector('.pet-error')?.textContent.includes('墨量不足')") && (await paperIds()).length === 0)
  const repaired = await agent.tool('canvas_draw', { svg: '<circle cx="40" cy="40" r="12" fill="#333333"/>', spaceId: limitedSpace.id, taskId: limitedTask.taskId, contextId: limitedTask.contextId })
  check('被拒任务仍可修稿且严格校验去填充', repaired.previewId && repaired.removed.includes('填充'))
  await page.click('揉掉草稿')
  await page.click('恢复试画限制')
  await page.setInput('textarea[aria-label="试画提示词"]', '测试取消之后不能落笔')
  await page.click('发送真实试画')
  const oldTask = (await agent.tool('turn_get_task')).task
  const oldSpace = (await agent.tool('canvas_find_space', { w: 120, h: 120 })).space
  await page.click('取消任务')
  await assert.rejects(() => agent.tool('canvas_draw', { svg, spaceId: oldSpace.id, taskId: oldTask.taskId, contextId: oldTask.contextId }), /过期|缺少|stale_context/)
  check('取消任务废弃旧帧并拒绝迟到画作', (await paperIds()).length === 0)
  await page.click('连接', '.pet-tabs button')
  await page.click('断开连接')
  await until(async () => !(await health()).game, '主动断开')
  await page.click('试画与调试', '.pet-tabs button')
  check('断开后禁止发任务且没有假图', await page.js("[...document.querySelectorAll('button')].find(button=>button.textContent==='发送真实试画').disabled") && (await paperIds()).length === 0)
  await page.click('连接', '.pet-tabs button')
  await page.click('重新连接')
  await until(() => page.js("document.querySelector('.pet-head').textContent.includes('真实 Agent 已连接')"), '主动重连')
  const beforeRoomConnections = await socketCount()
  await page.click('开始茶会', '.main-menu button')
  await page.click('创建房间', '.sheet-actions button')
  await page.waitScreen('lobby')
  await until(() => agent.tool('room_state').then(value=>value.context === 'idle'), '大厅无绘画上下文')
  check('进入大厅保持Agent在线', (await health()).agentAwake && (await health()).game && await socketCount() === beforeRoomConnections)
  await page.click('开始', '.anchor.a-br button.primary')
  await page.waitScreen('game')
  const game = await until(() => agent.tool('room_state').then(value=>value.context === 'game' ? value : null), '正式对局绑定')
  check('进入对局复用原连接且试画内容不污染房间', await socketCount() === beforeRoomConnections && (await page.opIds()).length === 0 && game.contextId !== task.contextId)
  await assert.rejects(() => agent.tool('canvas_draw', { svg, targetId: targets[0].id, contextId: task.contextId, taskId: task.taskId }), /过期|stale_context/)
  check('试画迟到任务不能写入对局', (await page.opIds()).length === 0)
  await page.setInput('.pb-input input', '正式房间风格检查')
  await page.key('Enter')
  const gameTask = (await agent.tool('turn_get_task')).task
  check('个人绘画风格带入正式房间', gameTask.text === '正式房间风格检查' && gameTask.profilePrompt.includes('简笔卡通') && gameTask.profilePrompt.includes('三个主要形状'))
  const space = (await agent.tool('canvas_find_space', { w: 160, h: 160 })).space
  const gameDraft = await agent.tool('canvas_draw', { svg: '<circle cx="60" cy="60" r="30" fill="none" stroke="#333333" stroke-width="3"/>', spaceId: space.id })
  await page.key('Tab')
  await until(async () => (await page.opIds()).length > 0, '正式对局盖章')
  check('正式房间保留原Host权限及草稿流程', !!gameDraft.previewId && (await page.opIds()).length === 1)
  await page.click('结束本局', '.tb-right button')
  await page.waitScreen('result')
  check('结算后Agent仍在线', (await health()).game && await socketCount() === beforeRoomConnections)
  await page.click('回到茶桌')
  await page.waitScreen('lobby')
  await page.click('返回')
  await page.waitScreen('home')
  await page.click('我的茶宠', '.main-menu button')
  await until(() => page.js("!!document.querySelector('.pet-workbench')"), '返回工作台')
  check('回到主页复用连接并恢复试画上下文', await socketCount() === beforeRoomConnections && (await agent.tool('room_state')).context === 'sandbox')
  check('试画限制没有污染正式房规', game.rules.penSpeed === 900 && game.rules.svgPreset === 'standard')
  check('页面无运行异常', page.errors.length === 0, page.errors)
  await page.shot('pet-02-return-home')
  writeFileSync(path.join(output, 'pet-workbench-summary.json'), JSON.stringify({ passed: checks.length, checks }, null, 2))
  console.log(`通过 ${checks.length} 项茶宠真实链路回归`)
} finally { await f.close() }
